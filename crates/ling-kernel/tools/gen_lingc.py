"""Generate ling-kernel/src/lingc/{lexer,ast,parser,entry,ir,lower}.rs as no_std
copies of the Ling front end (ling/src/lexer, src/parser, src/entry, src/mir)
and the MIR IR types (crates/ling-mir/src/ir.rs). Mechanical edits only:
alloc preludes, BTreeMap/BTreeSet for HashMap/HashSet, local Span/UnOp,
module paths. The interpreter itself is hand-written (interp.rs)."""
import os, re

# tools/ -> ling-kernel/ -> crates/ -> the ling repo root
LING = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.join(LING, r"crates\ling-kernel\src\lingc")
os.makedirs(OUT, exist_ok=True)

def rd(rel):
    return open(os.path.join(LING, rel), encoding="utf-8").read()

def wr(name, text, header):
    text = header + text
    open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", name, text.count("\n"), "lines")

HEAD = "//! GENERATED by crates/ling-kernel/tools/gen_lingc.py from {src} — the Ling front end as\n//! no_std (alloc) code for the in-kernel `ling run`. Re-run the generator to\n//! refresh; edit the originals, not this file.\n\n"

# ── lexer (mod.rs + token.rs) ─────────────────────────────────────────────────
lex = rd(r"src\lexer\mod.rs")
tok = rd(r"src\lexer\token.rs")
lex = lex.replace("// src/lexer/mod.rs — hand-written polyglot lexer\nmod cursor;\nmod token;\nmod unicode;\n\npub use cursor::Cursor;\npub use token::Token;\n", "")
lex = lex.replace("std::string::String", "String")
tok = tok.replace("// src/lexer/token.rs\n", "").replace("std::string::String", "String")
pre = "use alloc::string::{String, ToString};\n\n"
wr("lexer.rs", pre + tok + "\n" + lex, HEAD.format(src="src/lexer"))

# ── ast ──────────────────────────────────────────────────────────────────────
ast = rd(r"src\parser\ast.rs").replace("// src/parser/ast.rs\n", "")
# the MIR derives Eq on nodes holding a BinOp, and the interpreter copies it
ast = re.sub(r"#\[derive\(([^)]*)\)\]\npub enum BinOp", "#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum BinOp", ast)
ast += """
/// Unary operators as the MIR lowering emits them (ling-ast's `UnOp`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UnOp {
    Neg,
    Not,
    Ref,
    Deref,
}
"""
wr("ast.rs", "use alloc::boxed::Box;\nuse alloc::string::String;\nuse alloc::vec::Vec;\n" + ast, HEAD.format(src="src/parser/ast.rs"))

# ── parser ───────────────────────────────────────────────────────────────────
par = rd(r"src\parser\mod.rs")
par = par.replace("// src/parser/mod.rs\npub mod ast;\npub mod grammar;\n\nuse crate::lexer::Token;\nuse ast::*;\n",
                  "use super::ast::*;\nuse super::lexer::{Lexer, Token};\n")
par = par.replace("crate::lexer::Lexer::new", "Lexer::new")
pre = "use alloc::boxed::Box;\nuse alloc::format;\nuse alloc::string::{String, ToString};\nuse alloc::vec;\nuse alloc::vec::Vec;\n"
wr("parser.rs", pre + par, HEAD.format(src="src/parser/mod.rs"))

# ── entry ────────────────────────────────────────────────────────────────────
ent = rd(r"src\entry.rs").replace("use crate::parser::ast::{Expr, Item};", "use super::ast::{Expr, Item};\nuse alloc::string::{String, ToString};")
wr("entry.rs", ent, HEAD.format(src="src/entry.rs"))

# ── ir (ling-mir) ────────────────────────────────────────────────────────────
ir = rd(r"crates\ling-mir\src\ir.rs")
ir = ir.replace("use ling_ast::ast::{BinOp, UnOp};\nuse ling_ast::Span;\nuse std::hash::{Hash, Hasher};\n",
                "use super::ast::{BinOp, UnOp};\n\n/// Source position — unused in the kernel (no diagnostics need it yet).\n#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub struct Span;\nimpl Span {\n    pub const DUMMY: Span = Span;\n}\n")
# drop the manual Hash impls and Hash derives
ir = re.sub(r"\nimpl Hash for \w+ \{.*?\n\}\n", "\n", ir, flags=re.S)
ir = ir.replace(", Hash)]", ")]")
pre = "use alloc::boxed::Box;\nuse alloc::string::String;\nuse alloc::vec;\nuse alloc::vec::Vec;\n"
wr("ir.rs", pre + ir, HEAD.format(src="crates/ling-mir/src/ir.rs"))

# ── lowering (src/mir/mod.rs: dedup_items + everything from the lowering mark) ─
mir = rd(r"src\mir\mod.rs")
a = mir.index("/// Keep the last definition of every top-level `fn`/`bind` name")
b = mir.index("/// Lower an already-flattened AST to optimized MIR.")
dedup = mir[a:b]
c = mir.index("// ─── AST → MIR lowering")
low = mir[c:]
low = low.replace("fn lower_program_with(", "pub fn lower_program_with(")
low = low.replace("pub fn dedup_items", "fn dedup_items")
body = dedup + low
body = body.replace("fn dedup_items(prog:", "pub fn dedup_items(prog:")
body = body.replace("parser::ast::", "ast::")
body = body.replace("ling_ast::ast::BinOp", "ast::BinOp")
body = body.replace("std::collections::HashMap", "BTreeMap").replace("HashMap", "BTreeMap")
body = body.replace("std::collections::HashSet", "BTreeSet").replace("HashSet", "BTreeSet")
body = body.replace("std::rc::Rc", "Rc").replace("std::mem::take", "core::mem::take")
body = body.replace("crate::entry::entry_name", "super::entry::entry_name")
body = body.replace("use parser::ast::Item;", "use ast::Item;")
pre = ("use super::ast;\nuse super::ir::*;\nuse alloc::boxed::Box;\nuse alloc::collections::{BTreeMap, BTreeSet};\n"
       "use alloc::format;\nuse alloc::rc::Rc;\nuse alloc::string::{String, ToString};\nuse alloc::vec;\nuse alloc::vec::Vec;\n\n")
wr("lower.rs", pre + body, HEAD.format(src="src/mir/mod.rs"))
